/// تصنيف أجزاء المستند بحسب أثرها على ما يراه القارئ.
///
/// التصنيف ليس ترفًا تنظيميًا: هو أساس الفصل بين **ألوان الهوية الفعلية**
/// و**ضجيج الثيم الموروث** (`02` §6). لون لا يظهر إلا في تعريفات الأنماط
/// غالبًا موروث، ولون في المتن أو الشريحة قرار مصمّم.
///
/// **مشترك بين الصيغ عمدًا:** الفصل نفسه يلزم في Word وPowerPoint، والواجهة
/// تعرضه بمنطق واحد. أمّا *أيّ جزء ينتمي لأيّ صنف* فقرار كل صيغة وحدها.
library;

enum PartClass {
  /// ما يقرأه القارئ: المتن والترويسات والتذييلات، أو الشرائح.
  content,

  /// تعريفات الأنماط — مصدر أغلب الألوان الموروثة.
  styles,

  /// القوائم والترقيم.
  numbering,

  /// لوحة الثيم.
  theme,

  /// جزء لا نفحصه.
  other,
}
